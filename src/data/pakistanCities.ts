export function findPakistanCity(name: string): PakistanCity | undefined {
  const q = name.trim().toLowerCase();
  return PAKISTAN_CITIES.find(c => c.name.toLowerCase() === q);
}

export function searchPakistanCities(query: string, limit = 8): PakistanCity[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return PAKISTAN_CITIES.filter(c => c.name.toLowerCase().includes(q)).slice(0, limit);
}
